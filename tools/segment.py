#!/usr/bin/env python3
"""Line-preserving segmenter (plan 7.1, R1 to R9, R4, R5, R7, R8, invariant I1/T0).

A file is split on "\\n" into BLOCKS that partition its lines exactly (every line belongs to one block).
Each block is either translatable (a segment) or withheld:

  segments   heading, paragraph, list_item, table_row, frontmatter (allowlisted keys only)
  withheld   blank, frontmatter_keep, fence, comment, generated, rule, table_sep, inert
  mermaid    a fence whose LABELS are segments (kind mermaid_label: accTitle, accDescr, node, edge, subgraph,
             participant, message, note, block, state and transition text, R6). The rest of the diagram (type,
             node IDs, arrows, shapes, classDef) is the skeleton and is never touched (tools/mermaid.py, I5).

A segment keeps what it must not change outside its text: per-line PREFIXES (indentation, "> ", list
markers, "## ", "key: \\"") and a SUFFIX (trailing whitespace, closing "#"s, closing quote). Nothing is
reflowed, re-padded or re-escaped, so a target that equals the source reproduces the file byte for byte
(T0). Only the lines of a translated block are rewritten (R2).

Masking uses tools/mask.py (R3, R4): placeholders are numbered per segment, so a moved paragraph keeps
its placeholders. Segment ids are s-<12 hex of sha256(English text)>-<4-digit position> (R7).

Usage:
  python3 -I tools/segment.py --t0            T0 on every hand-written Markdown file (exit 0 = all identical)
  python3 -I tools/segment.py FILE.md         one-line summary of the segmentation
  python3 -I tools/segment.py --json FILE.md  segments as JSON (what the translate step reads)
"""
import hashlib
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import mask  # noqa: E402
import mermaid  # noqa: E402

# Front matter keys whose double-quoted scalar values are translated. R5 lists teaches, machine, state and
# name; title and applies-because are added because the generators copy them into prose (provisional
# decision, iteration 25). analogies/counterexamples are slug lists (identifiers) and are never extracted.
FM_TRANSLATE_KEYS = ("title", "name", "teaches", "machine", "state", "applies-because")

SEGMENT_KINDS = ("frontmatter", "heading", "paragraph", "list_item", "table_row")
SINGLE_LINE_KINDS = ("frontmatter", "heading", "table_row")
ENTITY_RE = re.compile(r"#(?:[A-Za-z]+|\d+);")  # Mermaid entities such as the gt, lt and quot ones

QUOTE_RE = re.compile(r"^(?P<q>(?: {0,3}>[ ]?)+)")
FENCE_RE = re.compile(r"^\s*(?P<f>`{3,}|~{3,})(?P<info>.*)$")
HEAD_RE = re.compile(r"^(?P<pre> {0,3}#{1,6}(?:[ \t]+|$))(?P<txt>.*?)(?P<suf>(?:[ \t]+#+)?[ \t]*)$")
RULE_RE = re.compile(r"^ {0,3}(?:(?P<c>[-*_])(?: *(?P=c)){2,}|=+) *$")
LIST_RE = re.compile(r"^(?P<pre>[ ]*(?:[-*+]|(?P<num>\d{1,9})[.)])[ \t]+)(?=\S)")
TABLE_SEP_RE = re.compile(r"^\s*\|(?:\s*:?-+:?\s*\|)+\s*$")
FM_FIELD_RE = re.compile(r'^(?P<pre>(?P<key>[A-Za-z][A-Za-z0-9_-]*):[ \t]*")(?P<val>.*)(?P<suf>"[ \t]*)$')
ESCAPE_RE = re.compile(r"\\.")
BEGIN_GEN_RE = re.compile(r"^\s*<!--\s*BEGIN GENERATED\b")
END_GEN_RE = re.compile(r"<!--\s*END GENERATED\b")
GENERATED_FILE_RE = re.compile(r"^<!-- GENERATED by ")
LETTER_RE = re.compile(r"[^\W\d_]")
LEADING_WS_RE = re.compile(r"^[ \t]*")
CONT_PREFIX_RE = re.compile(r"^(?P<q>(?: {0,3}>[ ]?)*)(?P<w>[ ]*)(?:[-*+]|\d{1,9}[.)])(?P<s>[ \t]+)$")


class SegmentError(ValueError):
    """The file has a construct the segmenter does not handle. Fails closed; never guesses."""


class Block:
    __slots__ = ("kind", "start", "end", "lines", "prefixes", "suffix", "text", "translate",
                 "masked", "mapping", "id", "info", "labels")

    def __init__(self, kind, start, lines, prefixes=None, suffix="", text=None, info=""):
        self.kind = kind
        self.start = start                     # 0-based first line
        self.end = start + len(lines) - 1      # 0-based last line (inclusive)
        self.lines = lines                     # original lines, no EOL
        self.prefixes = prefixes or []         # one per line, segments only
        self.suffix = suffix
        self.text = text                       # joined text of a segment (prefixes and suffix removed)
        self.info = info
        self.translate = False
        self.masked = None
        self.mapping = {}
        self.id = None
        self.labels = []                       # mermaid blocks only: Label objects

    def to_dict(self):
        d = {"kind": self.kind, "start": self.start + 1, "end": self.end + 1, "translate": self.translate}
        if self.kind == "mermaid":
            d["labels"] = [lab.to_dict() for lab in self.labels]
        if self.kind in SEGMENT_KINDS:
            d.update(prefixes=self.prefixes, suffix=self.suffix, text=self.text)
        if self.translate:
            d.update(segment_id=self.id, english_masked=self.masked,
                     placeholders=list(self.mapping))
        return d


class Label:
    """One translatable piece of a Mermaid diagram: a column range inside one line of a mermaid block."""
    kind = "mermaid_label"
    __slots__ = ("start", "span", "text", "info", "translate", "masked", "mapping", "id")

    def __init__(self, start, span):
        self.start = start                     # 0-based absolute line
        self.span = span                       # mermaid.Span (columns inside that line)
        self.text, self.info = span.text, span.role
        self.translate, self.masked, self.mapping, self.id = False, None, {}, None

    def to_dict(self):
        d = {"kind": self.kind, "role": self.info, "start": self.start + 1, "translate": self.translate,
             "text": self.text}
        if self.translate:
            d.update(segment_id=self.id, english_masked=self.masked, placeholders=list(self.mapping))
        return d


# ------------------------------------------------------------------ line classification

def split_quote(line):
    m = QUOTE_RE.match(line)
    q = m.group("q") if m else ""
    return q, line[len(q):]


def is_whole_comment_start(line):
    return line.strip().startswith("<!--")


def fence_open(line):
    m = FENCE_RE.match(line)
    if not m:
        return None
    if m.group("f")[0] == "`" and "`" in m.group("info"):
        return None  # inline code span that happens to start the line
    return m.group("f"), m.group("info").strip()


def fence_closes(line, fence):
    s = line.strip()
    return len(s) >= len(fence) and s[0] == fence[0] and s.strip(fence[0]) == ""


def interrupts(line, quote):
    """True if `line` cannot continue a paragraph whose quote prefix is `quote`."""
    q, rest = split_quote(line)
    if q.strip() != quote.strip() or not rest.strip():
        return True
    if fence_open(line) or is_whole_comment_start(line) or BEGIN_GEN_RE.match(line):
        return True
    if RULE_RE.match(rest) or HEAD_RE.match(rest) or mask.TABLE_RE.match(rest):
        return True
    m = LIST_RE.match(rest)
    if m and (m.group("num") is None or m.group("num") == "1"):
        return True
    return False


# ------------------------------------------------------------------ the segmenter

def split_lines(text):
    if "\r" in text:
        if text.count("\r") != text.count("\r\n") or text.count("\r\n") != text.count("\n"):
            raise SegmentError("mixed or lone CR line endings")
        return text.replace("\r\n", "\n").split("\n"), "\r\n"
    return text.split("\n"), "\n"


def front_matter_blocks(lines):
    """Blocks for a leading '---' front matter, and the index of the first body line."""
    try:
        end = lines.index("---", 1)
    except ValueError:
        raise SegmentError("front matter is not closed") from None
    blocks = [Block("frontmatter_keep", 0, ["---"])]
    keep = []
    keep_start = 1

    def flush():
        if keep:
            blocks.append(Block("frontmatter_keep", keep_start, list(keep)))
            keep.clear()

    for i in range(1, end):
        m = FM_FIELD_RE.match(lines[i])
        if m and m.group("key") in FM_TRANSLATE_KEYS:
            flush()
            blocks.append(Block("frontmatter", i, [lines[i]], [m.group("pre")], m.group("suf"),
                                m.group("val"), info=m.group("key")))
            keep_start = i + 1
        else:
            if not keep:
                keep_start = i
            keep.append(lines[i])
    flush()
    blocks.append(Block("frontmatter_keep", end, ["---"]))
    return blocks, end + 1


def segment_lines(lines):
    n = len(lines)
    blocks = []
    i = 0
    if lines and lines[0] == "---":
        blocks, i = front_matter_blocks(lines)
    in_list = False
    prev_blank = True
    while i < n:
        line = lines[i]
        if BEGIN_GEN_RE.match(line):
            j = i
            while j < n and not END_GEN_RE.search(lines[j]):
                j += 1
            if j >= n:
                raise SegmentError("line %d: BEGIN GENERATED without END" % (i + 1))
            blocks.append(Block("generated", i, lines[i:j + 1]))
            i, prev_blank = j + 1, False
            continue
        fo = fence_open(line)
        if fo:
            j = i + 1
            while j < n and not fence_closes(lines[j], fo[0]):
                j += 1
            if j >= n:
                raise SegmentError("line %d: unterminated code fence" % (i + 1))
            kind = "mermaid" if fo[1].lower().startswith("mermaid") else "fence"
            blk = Block(kind, i, lines[i:j + 1], info=fo[1])
            if kind == "mermaid":
                try:
                    blk.labels = [Label(i + 1 + sp.line, sp) for sp in mermaid.extract(blk.lines[1:-1])]
                except mermaid.MermaidError as e:
                    raise SegmentError("line %d: mermaid: %s" % (i + 1, e)) from None
            blocks.append(blk)
            i, prev_blank = j + 1, False
            continue
        s = line.strip()
        if s.startswith("<!--"):
            whole = s.endswith("-->") and s.count("<!--") == 1 and s.count("-->") == 1
            if whole or "-->" not in s:  # otherwise: prose that starts with an inline comment
                j = i
                while j < n and "-->" not in lines[j]:
                    j += 1
                if j >= n:
                    raise SegmentError("line %d: unterminated HTML comment" % (i + 1))
                blocks.append(Block("comment", i, lines[i:j + 1]))
                i, prev_blank = j + 1, False
                continue
        q, rest = split_quote(line)
        if not rest.strip():
            blocks.append(Block("blank", i, [line]))
            i, prev_blank = i + 1, True
            continue
        indent = len(rest) - len(rest.lstrip(" "))
        lm = LIST_RE.match(rest)
        if not lm and indent == 0:
            in_list = False
        if indent >= 4 and prev_blank and not in_list and not lm:
            raise SegmentError("line %d: indented code block is not supported" % (i + 1))
        if RULE_RE.match(rest):
            blocks.append(Block("rule", i, [line]))
            i, prev_blank = i + 1, False
            continue
        hm = HEAD_RE.match(rest)
        if hm:
            if hm.group("txt").strip():
                blocks.append(Block("heading", i, [line], [q + hm.group("pre")], hm.group("suf"), hm.group("txt")))
            else:
                blocks.append(Block("rule", i, [line]))
            i, prev_blank = i + 1, False
            continue
        if mask.TABLE_RE.match(rest):
            if TABLE_SEP_RE.match(rest):
                blocks.append(Block("table_sep", i, [line]))
            else:
                body = rest.rstrip()
                pre = q + LEADING_WS_RE.match(rest).group(0)
                blocks.append(Block("table_row", i, [line], [pre], rest[len(body):], body[len(pre) - len(q):]))
            i, prev_blank = i + 1, False
            continue
        # paragraph or list item: gather continuation lines
        if lm:
            in_list = True
            first_pre = q + lm.group("pre")
        else:
            first_pre = q + LEADING_WS_RE.match(rest).group(0)
        j = i + 1
        while j < n and not interrupts(lines[j], q):
            j += 1
        raw = lines[i:j]
        prefixes = [first_pre]
        for k in range(i + 1, j):
            qk, rk = split_quote(lines[k])
            prefixes.append(qk + LEADING_WS_RE.match(rk).group(0))
        parts = [ln[len(p):] for ln, p in zip(raw, prefixes)]
        last = parts[-1].rstrip()
        suffix = parts[-1][len(last):]
        parts[-1] = last
        blocks.append(Block("list_item" if lm else "paragraph", i, raw, prefixes, suffix, "\n".join(parts)))
        i, prev_blank = j, False
    return blocks


class Segmentation:
    def __init__(self, text, path=""):
        self.path = path
        lines, self.eol = split_lines(text)
        self.generated_file = bool(lines and GENERATED_FILE_RE.match(lines[0]))
        if self.generated_file:
            # Rule 4: generated files are never translated by hand; the generator owns them.
            self.blocks = [Block("generated", 0, lines)]
        else:
            self.blocks = segment_lines(lines)
        self._mask()

    def _mask(self):
        mk = mask.Masker()
        pos = 0
        for b in self.blocks:
            if b.kind == "mermaid":
                items = b.labels
            elif b.kind in SEGMENT_KINDS:
                items = [b]
            else:
                continue
            for it in items:
                mk.counter, mk.mapping = 0, {}
                if it.kind == "frontmatter":
                    masked = self._mask_escapes(mk, it.text, ESCAPE_RE)
                elif it.kind == "mermaid_label":
                    masked = self._mask_escapes(mk, it.text, ENTITY_RE, "ENT")
                else:
                    masked = mk.mask_line(it.text, table=(it.kind == "table_row"))
                if not LETTER_RE.search(mask.PH_RE.sub("", masked)):
                    continue  # nothing to translate: numbers, code, markup only
                it.translate, it.masked, it.mapping = True, masked, mk.mapping
                digest = hashlib.sha256(it.text.encode("utf-8")).hexdigest()[:12]
                it.id = "s-%s-%04d" % (digest, pos)
                pos += 1

    @staticmethod
    def _mask_escapes(mk, value, pattern, kind="ESC"):
        out, last = [], 0
        for m in pattern.finditer(value):
            out.append(mk.mask_line(value[last:m.start()]))
            out.append(mk._new(kind, m.group(0)))
            last = m.end()
        out.append(mk.mask_line(value[last:]))
        return "".join(out)

    def segments(self):
        out = []
        for b in self.blocks:
            if b.kind == "mermaid":
                out.extend(lab for lab in b.labels if lab.translate)
            elif b.translate:
                out.append(b)
        return out

    def original_lines(self):
        return [ln for b in self.blocks for ln in b.lines]

    def reassemble(self, targets=None):
        """Rebuild the file. `targets` maps segment id -> translated MASKED text (default: identity).

        Each target is checked with invariant I2 before it is unmasked; a failing target raises ValueError.
        """
        targets = targets or {}
        unknown = set(targets) - {b.id for b in self.segments()}
        if unknown:
            raise ValueError("targets for unknown segment ids: %s" % ", ".join(sorted(unknown)))
        mk = mask.Masker([])
        out = []
        for b in self.blocks:
            if b.kind == "mermaid":
                out.extend(self._render_mermaid(b, targets, mk))
                continue
            if not b.translate:
                out.extend(b.lines)
                continue
            tgt = targets.get(b.id, b.masked)
            problems = mask.check_placeholders(b.masked, tgt)
            if problems:
                raise ValueError("I2 failed for %s: %s" % (b.id, "; ".join(problems)))
            mk.mapping = b.mapping
            out.extend(render_block(b, mk.unmask(tgt)))
        return self.eol.join(out)

    @staticmethod
    def _render_mermaid(b, targets, mk):
        """Lines of a mermaid fence with the targeted labels replaced; the skeleton is copied untouched."""
        if not any(lab.id in targets for lab in b.labels if lab.translate):
            return b.lines
        texts = []
        for lab in b.labels:
            if not lab.translate or lab.id not in targets:
                texts.append(lab.text)
                continue
            tgt = targets[lab.id]
            problems = mask.check_placeholders(lab.masked, tgt)
            problems += mermaid.label_problems(lab.span, tgt)
            if problems:
                raise ValueError("I2/I10 failed for %s: %s" % (lab.id, "; ".join(problems)))
            mk.mapping = lab.mapping
            text = mk.unmask(tgt)
            problems = mermaid.label_problems(lab.span, text)
            if problems:
                raise ValueError("I10 failed for %s after restore: %s" % (lab.id, "; ".join(problems)))
            texts.append(text)
        body = mermaid.apply_spans(b.lines[1:-1], [lab.span for lab in b.labels], texts)
        return [b.lines[0]] + body + [b.lines[-1]]

    def to_dict(self):
        return {"file": self.path, "eol": self.eol, "blocks": [b.to_dict() for b in self.blocks]}


def continuation_prefix(prefix):
    """Prefix for extra lines when a target has more lines than the source segment."""
    m = CONT_PREFIX_RE.match(prefix)
    if m:  # keep any "> " quote part, turn the list marker into spaces of the same width
        return m.group("q") + " " * (len(prefix) - len(m.group("q")))
    return prefix


def render_block(block, text):
    """Lines for `block` with `text` as its content (unmasked). Same line count reuses the exact prefixes."""
    new = text.split("\n")
    if block.kind in SINGLE_LINE_KINDS and len(new) != 1:
        raise ValueError("%s segment must stay on one line" % block.kind)
    if len(new) == len(block.prefixes):
        prefixes = block.prefixes
    else:
        cont = block.prefixes[1] if len(block.prefixes) > 1 else continuation_prefix(block.prefixes[0])
        prefixes = [block.prefixes[0]] + [cont] * (len(new) - 1)
    lines = [p + t for p, t in zip(prefixes, new)]
    lines[-1] += block.suffix
    return lines


# ------------------------------------------------------------------ T0

def check_roundtrip(text, path=""):
    """T0 for one file. Returns a list of problem strings (empty = identical on all three levels)."""
    problems = []
    try:
        seg = Segmentation(text, path)
    except SegmentError as e:
        return ["segmenter refused: %s" % e]
    lines, eol = split_lines(text)
    if seg.original_lines() != lines:
        problems.append("blocks do not partition the file's lines")
    for b in seg.blocks:
        if b.kind in SEGMENT_KINDS and render_block(b, b.text) != b.lines:
            problems.append("lines %d-%d: prefix/text/suffix do not rebuild the source" % (b.start + 1, b.end + 1))
    for b in seg.blocks:
        if b.kind == "mermaid":
            body = b.lines[1:-1]
            if mermaid.apply_spans(body, [x.span for x in b.labels], [x.text for x in b.labels]) != body:
                problems.append("lines %d-%d: mermaid labels do not rebuild the source" % (b.start + 1, b.end + 1))
    try:
        back = seg.reassemble()
    except ValueError as e:
        return problems + ["masked round trip failed: %s" % e]
    if back != text:
        problems.append("identity round trip changed the file")
    return problems


def authored_files(root=ROOT):
    import inventory
    return [p for p in inventory.list_files(root) if "authored" in inventory.classify(p)]


def read_raw(path):
    with open(path, encoding="utf-8", newline="") as f:
        return f.read()


def main(argv):
    if len(argv) >= 2 and argv[1] == "--t0":
        files = argv[2:] or authored_files()
        bad = 0
        for p in files:
            full = p if os.path.isabs(p) or os.path.exists(p) else os.path.join(ROOT, p)
            probs = check_roundtrip(read_raw(full), p)
            if probs:
                bad += 1
                print("FAIL %s: %s" % (p, "; ".join(probs)))
        print("T0 %s: %d file(s), %d failing" % ("FAILED" if bad else "OK", len(files), bad))
        return 1 if bad else 0
    as_json = len(argv) == 3 and argv[1] == "--json"
    if as_json or len(argv) == 2:
        path = argv[-1]
        try:
            seg = Segmentation(read_raw(path), path)
        except SegmentError as e:
            print("FAIL %s" % e)
            return 1
        if as_json:
            print(json.dumps(seg.to_dict(), ensure_ascii=False, indent=2))
        else:
            kinds = {}
            for b in seg.blocks:
                kinds[b.kind] = kinds.get(b.kind, 0) + 1
            print("%s: %d blocks, %d translatable segments (%s)" % (
                path, len(seg.blocks), len(seg.segments()),
                ", ".join("%s %d" % kv for kv in sorted(kinds.items()))))
        return 0
    print(__doc__.split("Usage:")[1].rstrip())
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
